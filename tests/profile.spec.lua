local P=require('../src/Profile')
local passed=0
local function test(name,f) local ok,err=pcall(f);assert(ok,name..': '..tostring(err));passed=passed+1;print('PASS profile '..name) end
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function ready(p)
 local m=P.milestone(p);p.run.saleEarnings=m.earnings;p.run.wins[m.field]=m.wins
end
local depot={atDepot=true,activeEncounter=false,confirmed=true}
test('fresh profile owns exactly one permanent Blue with separate empty run',function()
 local p=P.new(44,123);eq(#p.fleet,1);eq(p.fleet[1].type,'Blue');eq(p.prestiges,0);eq(p.run.credits,0);eq(P.cargoUnits(p),0);eq(#p.run.cards,0);eq(p.run.index,1);eq(P.validate(p,44),true)
end)
test('base identity and type deterministic over loads',function()
 local p=P.new(44,123);local loaded=P.migrate(p,44);assert(loaded)
 eq(loaded.fleet[1].id,p.fleet[1].id);eq(loaded.fleet[1].base.maxStep60,p.fleet[1].base.maxStep60);assert(loaded~=p)
end)
test('failed malformed future and foreign loads never create defaults',function()
 eq(P.migrate(nil,44),nil);eq(P.migrate('corrupt',44),nil);local p=P.new(44,123);p.schemaVersion=99;eq(P.migrate(p,44),nil)
 p=P.new(44,123);eq(P.migrate(p,45),nil);p.fleet={};eq(P.migrate(p,44),nil)
end)
test('supported v1 migrates without rerolling permanent traits',function()
 local p=P.new(44,123);p.schemaVersion=1;p.run.entitlements=nil;p.run.yieldRemainders=nil;p.run.offersWithoutCombat=nil
 local n=P.migrate(p,44);assert(n);eq(n.schemaVersion,2);eq(n.fleet[1].id,p.fleet[1].id);eq(n.fleet[1].base.maxHealth,p.fleet[1].base.maxHealth)
end)
test('cargo cap, material sale value and earned progress exact',function()
 local p=P.new(44,123);eq(P.addCargo(p,'Quartz',100,120),100);eq(P.addCargo(p,'Cobalt',100,120),20);eq(P.cargoUnits(p),120)
 local ok,r=P.sell(p,{Quartz=1,Cobalt=4},'sell:1',p.run.id);eq(ok,true);eq(r.credits,180);eq(p.run.credits,180);eq(p.run.saleEarnings,180);eq(P.cargoUnits(p),0)
end)
test('duplicate sale receipt cannot sell the next cargo a second time',function()
 local p=P.new(44,123);P.addCargo(p,'Ruby',10,120);P.sell(p,{Ruby=2},'sell:1',p.run.id);P.addCargo(p,'Ruby',10,120)
 local ok,r=P.sell(p,{Ruby=2},'sell:1',p.run.id);eq(ok,true);eq(r.credits,20);eq(P.cargoUnits(p),10);eq(p.run.credits,20)
end)
test('unknown material and invalid cargo cannot erase inventory',function()
 local p=P.new(44,123);eq(P.addCargo(p,'Quartz',0/0,120),0);eq(P.addCargo(p,'Quartz',-1,120),0);P.addCargo(p,'Quartz',10,120)
 eq(P.sell(p,{},'bad-sale',p.run.id),false);eq(P.cargoUnits(p),10)
end)
test('prestige gate requires cumulative earnings and real clear',function()
 local p=P.new(44,123);p.run.credits=100000;eq(P.prestigePreview(p).eligible,false);p.run.saleEarnings=2000;eq(P.prestigePreview(p).eligible,false);p.run.wins.Cobalt=1;eq(P.prestigePreview(p).eligible,true)
end)
test('pending offer or own assault blocks prestige without mutation',function()
 local p=P.new(44,123);ready(p);p.run.pendingOffer={id='paid'};eq(P.prestige(p,'p1',p.run.id,depot),false);eq(#p.fleet,1)
 p.run.pendingOffer=nil;eq(P.prestige(p,'p2',p.run.id,{atDepot=true,activeEncounter=true,confirmed=true}),false);eq(#p.fleet,1)
 eq(P.prestige(p,'p3',p.run.id,{atDepot=true,confirmed=false}),false)
end)
test('prestige adds one, preserves IDs and resets every run channel',function()
 local p=P.new(44,123);ready(p);local id=p.fleet[1].id;local base=P.clone(p.fleet[1].base)
 p.run.credits=121;p.run.cargo={Ruby=10};p.run.cards={{cardId='D05',scope='Individual',targetDroneId=id,effects={startup=1}}};p.run.entitlements={Cobalt='old'};p.run.packIndex=5;p.run.offersWithoutCombat=2
 local ok,result=P.prestige(p,'prestige:1',p.run.id,depot);eq(ok,true);eq(result.droneType,'Red');eq(#p.fleet,2);eq(p.fleet[1].id,id);eq(p.fleet[1].base.maxStep60,base.maxStep60)
 eq(p.run.credits,0);eq(P.cargoUnits(p),0);eq(#p.run.cards,0);eq(p.run.packIndex,0);eq(p.run.offersWithoutCombat,0);eq(next(p.run.entitlements),nil);eq(p.run.saleEarnings,0);eq(p.run.index,2)
end)
test('duplicate prestige and stale old-run request never grant extra drones',function()
 local p=P.new(44,123);ready(p);local old=p.run.id;P.prestige(p,'prestige:1',old,depot)
 local ok,r=P.prestige(p,'prestige:1',old,depot);eq(ok,true);eq(r.fleetCount,2);eq(#p.fleet,2)
 eq(P.prestige(p,'prestige:2',old,depot),false);eq(#p.fleet,2)
end)
test('failed durable working-copy transition leaves old profile usable',function()
 local p=P.new(44,123);ready(p);local copy=P.clone(p);eq(P.prestige(copy,'p1',copy.run.id,depot),true)
 -- Simulated adapter rejects commit; only the working copy changed.
 eq(#p.fleet,1);eq(p.run.index,1);eq(p.run.saleEarnings,2000)
end)
test('six permanent units retained and deterministic type sequence',function()
 local p=P.new(44,123);local expected={'Blue','Red','Green','Blue','Red','Green'}
 for i=1,5 do ready(p);eq(P.prestige(p,'p'..i,p.run.id,depot),true) end
 eq(#p.fleet,6);for i,d in ipairs(p.fleet) do eq(d.type,expected[i]);eq(d.id,'44:drone:'..i) end;eq(P.validate(p,44),true)
end)
test('bounded receipts and monotonic run reject evicted prestige replay',function()
 local p=P.new(44,123);ready(p);local old=p.run.id;P.prestige(p,'p1',old,depot)
 for i=1,100 do P.record(p,'Other','x'..i,{ok=true}) end;eq(#p.receipts,64);eq(P.prestige(p,'p1',old,depot),false);eq(#p.fleet,2)
end)
print(passed..' profile tests passed')
test('missing-target paid offer migration refunds once without reroll',function()
 local p=P.new(44,123);p.run.credits=20;p.run.packIndex=1
 p.run.pendingOffer={id='44:run:1:pack:1',runId=p.run.id,price=80,choices={{cardId='D05',scope='Individual',targetDroneId='missing',effects={startup=1}},{cardId='F01',scope='Fleet',effects={mining=.15}},{cardId='F06',scope='Player',effects={capacity=.25}}}}
 local migrated=P.migrate(p,44);assert(migrated);eq(migrated.run.credits,100);eq(migrated.run.pendingOffer,nil);eq(migrated.run.packIndex,1)
 local twice=P.migrate(migrated,44);assert(twice);eq(twice.run.credits,100)
end)
print(passed..' FINAL profile tests passed')
test('foreign or mismatched permanent identity cannot load into another fleet',function()
 local p=P.new(44,123);p.fleet[1].id='99:drone:1';eq(P.migrate(p,44),nil)
 p=P.new(44,123);p.fleet[1].id='44:drone:2';eq(P.migrate(p,44),nil)
end)
test('isolated Studio preview supports negative test user IDs',function()
 local p=P.new(-1,123);eq(p.fleet[1].id,'-1:drone:1');eq(P.validate(p,-1),true)
end)
print(passed..' FINAL ownership/profile tests passed')
test('saved pending choices reject invalid scopes unknown effects and nonfinite modifiers',function()
 local function withOffer()
  local p=P.new(44,123);p.run.pendingOffer={id='44:run:1:pack:1',runId=p.run.id,price=80,choices={{cardId='F01',scope='Fleet',effects={mining=.15}},{cardId='F06',scope='Player',effects={capacity=.25}},{cardId='D05',scope='Individual',targetDroneId=p.fleet[1].id,effects={startup=1}}}};return p
 end
 local p=withOffer();p.run.pendingOffer.choices[1].scope='OtherPlayer';eq(P.validate(p,44),false)
 p=withOffer();p.run.pendingOffer.choices[1].effects={currency=100};eq(P.validate(p,44),false)
 p=withOffer();p.run.pendingOffer.choices[1].effects={mining=math.huge};eq(P.validate(p,44),false)
end)
print(passed..' COMPLETE profile tests passed')
test('saved run cards accept known rarity and legacy nil but reject foreign labels',function()
 local p=P.new(44,123);local c={cardId='F01',scope='Fleet',effects={mining=.15}};p.run.cards={c}
 for _,tier in ipairs({'Common','Uncommon','Rare'}) do c.rarity=tier;eq(P.validate(p,44),true);assert(P.migrate(p,44)) end
 c.rarity=nil;eq(P.validate(p,44),true);assert(P.migrate(p,44))
 c.rarity='Legendary';eq(P.validate(p,44),false);eq(P.migrate(p,44),nil)
end)
test('saved offer rejects invalid rarity without reroll or mutation',function()
 local p=P.new(44,123);p.run.credits=20;p.run.packIndex=1
 p.run.pendingOffer={id='44:run:1:pack:1',runId=p.run.id,price=80,choices={{cardId='F01',scope='Fleet',effects={mining=.15},rarity='Common'},{cardId='F06',scope='Player',effects={capacity=.25},rarity='Uncommon'},{cardId='D05',scope='Individual',targetDroneId=p.fleet[1].id,effects={startup=1},rarity='Rare'}}}
 eq(P.validate(p,44),true);local copy=P.migrate(p,44);assert(copy);eq(copy.run.pendingOffer.choices[3].rarity,'Rare')
 p.run.pendingOffer.choices[1].rarity=nil;eq(P.validate(p,44),true);assert(P.migrate(p,44))
 p.run.pendingOffer.choices[1].rarity='Legendary';eq(P.validate(p,44),false);eq(P.migrate(p,44),nil)
 eq(p.run.credits,20);eq(p.run.pendingOffer.choices[1].rarity,'Legendary');eq(p.run.packIndex,1)
end)
print(passed..' COMPLETE rarity and profile tests passed')

-- Production capability/target/phase functions, with no Roblox dependencies.
local R=require('../src/DroneRoles')
local passed=0
local function test(name,fn) local ok,err=pcall(fn);assert(ok,name..': '..tostring(err));passed+=1;print('PASS role '..name) end
local function node(id,hp,kind,x,extra)
 local n={id=id,hp=hp,maxHP=hp+10,kind=kind or 'Crystal',x=x or 0,y=0,z=0,readyAt=0}
 for key,value in pairs(extra or {}) do n[key]=value end
 return n
end
local origin={x=0,y=0,z=0}
test('only the ordinary miner grants a continuous mining capability',function()
 assert(R.isMiner('Striker'))
 for _,role in ipairs({'Charger','Dart','Courier','Medic','Orbiter','Scrapper','Unknown'}) do assert(not R.isMiner(role),role) end
end)
test('only the miner and breaker accept ordinary rock jobs or combat',function()
 for _,role in ipairs({'Striker','Charger'}) do assert(R.isWorker(role) and R.combat(role)) end
 for _,role in ipairs({'Dart','Courier','Medic','Orbiter','Scrapper','Unknown'}) do assert(not R.isWorker(role) and not R.combat(role),role) end
end)
test('each support role has one explicit job and hardware ability',function()
 assert(R.isGrower('Dart') and not R.isGrower('Striker'))
 assert(R.isCourier('Courier') and R.isHealer('Medic'))
 assert(R.ability('Orbiter')=='Orbital' and R.ability('Scrapper')=='Scrap' and R.ability('Dart')==nil)
 assert(R.job('Courier')=='Backpack emptier' and R.job('unknown')=='Unknown')
end)
test('legacy color identities map to existing jobs without erasing ownership',function()
 assert(R.canonical('Blue')=='Striker' and R.canonical('Red')=='Charger' and R.canonical('Green')=='Medic')
 assert(R.isMiner('Blue') and R.isWorker('Red') and R.isHealer('Green'))
end)
test('unknown and missing roles fail closed',function()
 assert(not R.isWorker(nil) and not R.isMiner(false) and not R.combat('Future'))
 assert(R.ability(nil)==nil)
end)
test('grower never selects or damages existing mineable rocks',function()
 local a=node('rock',160)
 assert(R.chooseTarget('Dart',{a},origin,10)==nil and a.hp==160)
 assert(R.job('Dart')=='Rock grower')
end)
test('breaker prioritizes a reachable shell over ordinary work',function()
 local crystal,shell=node('rock',150),node('shell',100,'Geode',3)
 assert(R.chooseTarget('Charger',{crystal,shell},origin,10)==shell)
end)
test('target selection excludes paid growing denied and malformed nodes',function()
 local good=node('good',40)
 local denied=node('no',1000,'Geode',0,{eligible=false})
 local paid=node('paid',1000,'Geode',0,{paid=true})
 local growing=node('growing',1000,'Geode',0,{readyAt=20})
 local nan=node('nan',0/0,'Geode')
 assert(R.chooseTarget('Charger',{denied,paid,growing,nan,good},origin,10)==good)
 assert(R.chooseTarget('Medic',{good},origin,10)==nil)
end)
test('target tie breaks remain deterministic across list order',function()
 local a,b=node('a',100),node('b',100)
 assert(R.chooseTarget('Charger',{b,a},origin,10)==a)
end)
test('breaker cannot wind up before actually arriving',function()
 local state=R.newBreaker('r',0)
 local phase,event=R.stepBreaker(state,10,{valid=true,arrived=false})
 assert(phase=='Approach' and event==nil and state.impactSerial==0)
end)
test('windup dive impact recovery each emit exactly once',function()
 local s=R.newBreaker('r',0)
 local phase,event=R.stepBreaker(s,0,{valid=true,arrived=true});assert(phase=='Windup' and event=='windup')
 phase,event=R.stepBreaker(s,.79,{valid=true});assert(phase=='Windup' and not event)
 phase,event=R.stepBreaker(s,.8,{valid=true});assert(phase=='Dive' and event=='dive')
 phase,event=R.stepBreaker(s,.81,{valid=true,impactReached=true});assert(phase=='Impact' and event=='contact' and s.impactSerial==0)
 phase,event=R.stepBreaker(s,.82,{valid=true,impactReached=true});assert(phase=='Impact' and not event and s.impactSerial==0)
 phase,event=R.stepBreaker(s,1.82,{valid=true});assert(phase=='Recover' and event=='impact' and s.impactSerial==1)
 phase,event=R.stepBreaker(s,2.48,{valid=true});assert(phase=='Complete' and event=='complete')
 phase,event=R.stepBreaker(s,10,{valid=true,impactReached=true});assert(phase=='Complete' and not event and s.impactSerial==1)
end)
test('a missed dive recovers without ever emitting an impact',function()
 local s=R.newBreaker('r',0);R.stepBreaker(s,0,{valid=true,arrived=true});R.stepBreaker(s,.8,{valid=true})
 local phase,event=R.stepBreaker(s,2.06,{valid=true,impactReached=false})
 assert(phase=='Recover' and event=='missed' and s.impactSerial==0)
end)
test('startup upgrades alter actual windup timing and pose together',function()
 local s=R.newBreaker('r',0,.2);R.stepBreaker(s,0,{valid=true,arrived=true})
 assert(R.breakerPose(s,.1).progress==.5)
 assert(R.stepBreaker(s,.19,{valid=true})=='Windup')
 assert(R.stepBreaker(s,.2,{valid=true})=='Dive')
 s=R.newBreaker('r',0);s.windup=.001;R.stepBreaker(s,0,{valid=true,arrived=true})
 assert(R.stepBreaker(s,.079,{valid=true})=='Windup' and R.stepBreaker(s,.08,{valid=true})=='Dive')
 s=R.newBreaker('r',0);s.windup=0/0;R.stepBreaker(s,0,{valid=true,arrived=true})
 assert(R.stepBreaker(s,.2,{valid=true})=='Windup')
end)
test('invalid or changed targets cancel any phase without damage',function()
 for _,now in ipairs({0,.4,1}) do
  local s=R.newBreaker('r',0);R.stepBreaker(s,0,{valid=true,arrived=true})
  local phase,event=R.stepBreaker(s,now,{valid=false,impactReached=true})
  assert(phase=='Canceled' and event=='canceled' and s.impactSerial==0)
 end
 local s=R.newBreaker('r',0);local phase=R.stepBreaker(s,.1,{valid=true,targetId='other',arrived=true});assert(phase=='Canceled')
end)
test('backward or nonfinite clocks cannot skip phases',function()
 local s=R.newBreaker('r',5)
 assert(R.stepBreaker(s,4,{valid=true,arrived=true})=='Approach')
 assert(R.stepBreaker(s,0/0,{valid=true,arrived=true})=='Approach')
end)
test('poses give bounded anticipation dive and recovery without movement authority',function()
 local s=R.newBreaker('r',0);R.stepBreaker(s,0,{valid=true,arrived=true})
 local first=R.breakerPose(s,0);local charged=R.breakerPose(s,.8)
 assert(first.lift==0 and charged.lift==1.2 and charged.dive==0)
 R.stepBreaker(s,.8,{valid=true});local dive=R.breakerPose(s,2);assert(dive.dive==1 and dive.lift==0)
 R.stepBreaker(s,2,{valid=true,impactReached=true});R.stepBreaker(s,3.01,{valid=true})
 local recovered=R.breakerPose(s,4);assert(recovered.dive==0 and recovered.progress==1)
end)
print(passed..' production role capability/phase checks passed; not engine motion or multiplayer evidence')

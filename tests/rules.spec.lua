local R=require('../src/Rules')
local passed=0
local function check(name,f)
 local ok,err=pcall(f);assert(ok,name..': '..tostring(err));passed=passed+1;print('PASS '..name)
end
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function drone(id,user)
 return {id=id or '1:blue-1',owner=user or 1,hp=80,state='Follow',life=1,
  permanent={type='Blue',base={maxHealth=80}},stats={miningDPS=30,warmup=.4},cargo=45,credits=120,readyAt=0}
end
local function active(two)
 local e=R.newEncounter({EncounterPrefix='server:field3'});local a=drone()
 R.gather(e,0);R.enroll(e,1,'run-1',{a})
 local b=drone('2:blue-1',2)
 if two then R.enroll(e,2,'run-2',{b}) end
 eq(R.step(e,4,two and 2 or 1,true,false,0),'start')
 return e,a,b
end
local function clear(two)
 local e,a,b=active(two);R.markContribution(e,1,'run-1')
 if two then R.markContribution(e,2,'run-2') end
 eq(R.step(e,5,two and 2 or 1,true,true,two and 2 or 1),'clear')
 return e,a,b
end
check('finite input validation rejects malformed values',function()
 for _,v in ipairs({0/0,math.huge,-math.huge,{},'3'}) do eq(R.finite(v),false) end
 eq(R.finite(3),true)
end)
check('ownership and destroyed/reprinting states reject commands',function()
 eq(R.allowed(1,2,'Mine'),false);eq(R.allowed(1,1,'Destroyed'),false)
 eq(R.allowed(1,1,'Reprinting'),false);eq(R.allowed(1,1,'Mine'),true)
end)
check('concurrent geode shell death is one atomic transition',function()
 local r={hp=2,paid=false};local shells=0
 for _=1,100 do if R.damage(r,1) then shells=shells+1 end end
 eq(shells,1);eq(r.hp,0);eq(r.paid,true)
end)
check('invalid damage cannot heal or prematurely reward',function()
 local r={hp=10,paid=false}
 for _,n in ipairs({-1,0,math.huge,-math.huge,0/0}) do eq(R.damage(r,n),false) end
 eq(r.hp,10);eq(r.paid,false)
end)
check('concurrent crystal finish rewards exactly one hit',function()
 local r={hp=1,paid=false};eq(R.damage(r,5),true);eq(R.damage(r,5),false)
end)
check('concurrent shell finish creates one set of child rewards',function()
 local shell={hp=1,paid=false};local children=0
 for _=1,3 do if R.damage(shell,2) then children=children+5 end end
 eq(children,5)
end)
check('new profile encounter accepts one drone and does not expect three',function()
 local e,a=active();eq(R.participates(e,a,'run-1'),true)
 local count=0;for _ in pairs(e.roster) do count=count+1 end;eq(count,1)
end)
check('finite cooperative roster locks user run and life identity',function()

 eq(R.participates(e,a,'run-1'),true);eq(R.participates(e,b,'run-2'),true)
 eq(R.enroll(e,3,'run-3',{drone('3:blue-1',3)}),false)
 eq(R.participates(e,a,'run-after-prestige'),false)
end)
check('roster enrollment snapshots stats rather than mutable card state',function()
 local e,a=active();a.stats.warmup=.1;a.stats.miningDPS=999
 eq(e.roster[a.id].stats.warmup,.4);eq(e.roster[a.id].stats.miningDPS,30)
end)
check('empty or wholly invalid enrollment does not spend user join',function()
 local e=R.newEncounter();R.gather(e,0)
 eq(R.enroll(e,1,'run-1',{}),false);eq(e.users[1],nil)
 local d=drone();d.hp=0;d.state='Reprinting'
 eq(R.enroll(e,1,'run-1',{d}),false);eq(next(e.roster),nil)
 d.hp=80;d.state='Follow';eq(R.enroll(e,1,'run-1',{d}),true)
end)

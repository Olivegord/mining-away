local Music=require('../src/MusicDirector')
local random={NextNumber=function(_,minimum) return minimum end}
local function observe(director,first,last,field,working)
 for now=first,last do director:observe(now,field,working) end
end

local director=Music.new(random,0)
observe(director,1,120,'Amber',false)
assert(not director:eligible(120),'standing in a field cannot cue music')
observe(director,121,180,'Amber',true)
observe(director,181,185,'Amber',false)
observe(director,186,199,'Amber',true)
assert(not director:eligible(199),'short travel gap is not mining time')
director:observe(200,'Amber',true)
assert(director:eligible(200)=='Amber')
director:observe(201,'Quartz',true)
assert(not director:eligible(201),'work from a different field carried over')
observe(director,202,250,'Quartz',true)
observe(director,251,263,'Quartz',false)
observe(director,264,300,'Quartz',true)
assert(not director:eligible(300),'a sustained work break should clear the streak')
observe(director,301,338,'Quartz',true)
assert(director:eligible(338)=='Quartz')
director:started('Quartz')
director:finished(400)
observe(director,339,549,'Quartz',true)
assert(not director:eligible(549) and director:eligible(550)=='Quartz','silence must follow song completion')

director=Music.new(random,0)
local function sale(at,id,full)
 director:sale(at,{id=id,cash=10,full=full})
end
sale(10,'prior',true)
sale(310,'courier',false)
sale(360,'first',true)
sale(365,'first',true)
sale(370,'second',true)
assert(not director:eligible(370),'old, duplicate and courier receipts cannot fill the streak')
sale(420,'third',true)
assert(director:eligible(420)=='Sell' and not director:eligible(476),'sale cues must expire')
director:started('Sell')
sale(430,'third',true)
sale(440,'fourth',true)
sale(450,'fifth',true)
assert(not director:eligible(450),'a completed sale cue must consume its streak')
sale(470,'sixth',true)
assert(director:eligible(470)=='Sell')
print('PASS field dwell, activity resets, song cooldown, and private sale streak scheduling')
